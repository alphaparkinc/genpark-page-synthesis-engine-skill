import json, sys
from client import SparkpageSynthesisEngineClient

def handle_mcp_request(payload):
    method = payload.get("method")
    req_id = payload.get("id", 1)
    if method == "initialize":
        return {"jsonrpc": "2.0", "id": req_id, "result": {"protocolVersion": "2024-11-05", "serverInfo": {"name": "sparkpage-synthesis-engine", "version": "1.0.0"}}}
    elif method == "tools/list":
        return {"jsonrpc": "2.0", "id": req_id, "result": {"tools": [{"name": "synthesize_page", "description": "Synthesize search results into a dynamic comparison matrix and Sparkpage layout."}]}}
    elif method == "tools/call":
        client = SparkpageSynthesisEngineClient()
        res = client.synthesize_page()
        return {"jsonrpc": "2.0", "id": req_id, "result": {"content": [{"type": "text", "text": json.dumps(res, indent=2)}]}}
    return {"jsonrpc": "2.0", "id": req_id, "result": {"status": "ACTIVE"}}

if __name__ == "__main__":
    if len(sys.argv) > 1 and sys.argv[1] == "--test":
        print(json.dumps(handle_mcp_request({"method": "tools/list"})))
    else:
        client = SparkpageSynthesisEngineClient()
        print(json.dumps(client.synthesize_page(), indent=2))
